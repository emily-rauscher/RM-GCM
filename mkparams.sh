#!/bin/sh
# Generate params.i and buildinfo.inc for one model configuration.
# Called by the makefile; normally run as part of "make", e.g.
#   make RES=T2 NL=100 RT=picket
#   make RES=T31 NL=50 RT=11
# Usage: mkparams.sh RES NL RT NDYE NTGRID NPGRID
#   RES     horizontal resolution: T2 or T31
#   NL      number of vertical levels
#   RT      picket (picket fence or double-gray) or a corr-k band
#           count (11, 30, 196, ...)
#   NDYE    number of cloud dye tracers
#   NTGRID, NPGRID  size of the corr-k T-P table grid
# Each file is rewritten only if its contents change, so an unchanged
# configuration triggers no recompilation.

usage() {
    echo "mkparams.sh: $1" >&2
    echo "usage: make RES=T2|T31 NL=<levels> RT=picket|<bands> NDYE=<n>" >&2
    exit 1
}

[ $# -eq 6 ] || usage "expected 6 arguments, got $#"
RES=$1; NL=$2; RT=$3; NDYE=$4; NTGRID=$5; NPGRID=$6

isint() { case $1 in ''|*[!0-9]*) return 1 ;; *) [ "$1" -gt 0 ] ;; esac; }

case $RES in
    T2)  NN=2;  MG=8;  JG=2;  NWJ2=2 ;;
    T31) NN=31; MG=96; JG=24; NWJ2=256 ;;
    *)   usage "unknown RES=$RES (T2 or T31)" ;;
esac
isint "$NL"     || usage "NL must be a positive integer, got '$NL'"
isint "$NDYE"   || usage "NDYE must be a positive integer, got '$NDYE'"
isint "$NTGRID" || usage "NTGRID must be a positive integer, got '$NTGRID'"
isint "$NPGRID" || usage "NPGRID must be a positive integer, got '$NPGRID'"

if [ "$RT" = picket ]; then
    # corrk.f is always compiled, so the corr-k sizes need values even
    # here; they are not used.
    NWNO=11
    RTLINE="     +,NWNO=$NWNO,NTGRID=$NTGRID,NPGRID=$NPGRID
     +,NKGAUSS=3,NIR=2,NSOL=3,NTOTAL=5,NBATCH=5)"
    RTDESC="picket fence or double-gray"
elif isint "$RT"; then
    NWNO=$RT
    RTLINE="     +,NWNO=$NWNO,NTGRID=$NTGRID,NPGRID=$NPGRID
     +,NKGAUSS=8,NIR=NKGAUSS*NWNO,NSOL=NIR,NTOTAL=NIR+NSOL
     +,NBATCH=2*NKGAUSS)"
    RTDESC="correlated-k, $NWNO bands"
    [ -d "${NWNO}bands/kcoeffs" ] || echo "mkparams.sh: warning: no" \
        "${NWNO}bands/kcoeffs here; the run's DATA_DIR must provide it" >&2
else
    usage "RT must be picket or a band count, got '$RT'"
fi

CFG="RES=$RES NL=$NL RT=$RT NDYE=$NDYE NTGRID=$NTGRID NPGRID=$NPGRID"

# Replace $1 by $1.tmp only if they differ.
update() {
    if cmp -s "$1.tmp" "$1"; then rm -f "$1.tmp"; else mv "$1.tmp" "$1"; fi
}

cat > params.i.tmp <<EOF
!     GENERATED by make ($CFG).
!     Do not edit: change the make command instead.
!     Untyped PARAMETERs only: most files include this before their
!     IMPLICIT statement (corrk.f types every name itself).
!     Number of cloud species (NCLOUDS):
      include 'nclouds.inc'
!     $RES, $NL levels, $RTDESC.
!     NTRAC is the number of SPECTRAL tracers: 1, water vapour only.
!     NDYE is the number of cloud dye tracers, on the Gaussian grid
!     (dyeadv.f), numbered 2..NDYE+1 with a radius ADYE(KK) each in
!     fort.7. KDYEMODE=2 needs NDYE even: NDYE = 2 x the number of
!     cloud species (KDYESPEC in fort.7), one vapour/solid pair each.
!     NWNO is the corr-k band count, NTGRID x NPGRID its k-table T-P
!     grid; NIR and NSOL count the RT channels (NKGAUSS per band).
      PARAMETER(NN=$NN,MM=$NN,NHEM=2, NL=$NL,MOCT=1,MG=$MG,JG=$JG,NWJ2=$NWJ2
     +,NCRAY=8,JGL=JG,NTRAC=1,NLEVRF=1,NDYE=$NDYE
$RTLINE
EOF
update params.i

cat > buildinfo.inc.tmp <<EOF
!     GENERATED by make: the configuration this binary was built with.
      CHARACTER(len=*), PARAMETER :: BUILDCFG =
     &    '$CFG'
EOF
update buildinfo.inc

printf 'RES = %s\nNL = %s\nRT = %s\nNDYE = %s\nNTGRID = %s\nNPGRID = %s\n' \
    "$RES" "$NL" "$RT" "$NDYE" "$NTGRID" "$NPGRID" > build.cfg.tmp
update build.cfg
